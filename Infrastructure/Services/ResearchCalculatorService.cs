using Microsoft.EntityFrameworkCore;
using GrindingThunder.Api.Application.Exceptions;
using GrindingThunder.Api.Application.Models;
using GrindingThunder.Api.Domain.Entities;
using GrindingThunder.Api.Domain.Services;
using GrindingThunder.Api.Infrastructure.Persistence;

namespace GrindingThunder.Api.Infrastructure.Services;

/// <summary>
/// Calculates the RP and SL required to obtain a target vehicle by traversing
/// the explicit prerequisite lines upwards and incorporating player-chosen
/// filler vehicles for rank-gate requirements.
/// When an explicit filler set leaves a rank-gate shortfall, the calculator
/// automatically selects eligible researchable candidates in that rank according
/// to the caller-selected ResearchOptimizationMode (Least RP, Least SL, Fewest
/// additional vehicles, or Estimated fewest matches).
/// </summary>
public class ResearchCalculatorService : IResearchCalculatorService
{
    private readonly ApplicationDbContext _context;

    public ResearchCalculatorService(ApplicationDbContext context)
    {
        _context = context;
    }

    public async Task<ResearchCalculationResult> CalculateResearchAsync(
        ResearchCalculationRequest request,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);

        if (request.AverageRpPerMatch <= 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(request.AverageRpPerMatch),
                "Average RP per match must be greater than zero.");
        }

        if (request.AverageNetSlPerMatch <= 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(request.AverageNetSlPerMatch),
                "Average net SL per match must be greater than zero.");
        }

        if (!Enum.IsDefined(request.OptimizationMode))
        {
            throw new ArgumentOutOfRangeException(
                nameof(request.OptimizationMode),
                $"Unknown research optimization mode: {request.OptimizationMode}.");
        }

        var unlockedSet = (request.UnlockedVehicleIds ?? new List<Guid>())
            .Distinct()
            .ToHashSet();

        var fillerTargetIds = (request.FillerTargetIds ?? new List<Guid>())
            .Distinct()
            .ToHashSet();

        // Load one complete, read-only snapshot. AsSplitQuery avoids a cartesian
        // product while keeping every query generated by this aggregate load
        // constrained by the caller-selected version.
        var version = await _context.ResearchTreeVersions
            .AsNoTracking()
            .AsSplitQuery()
            .Include(v => v.TreeRanks)
            .Include(v => v.Entries)
                .ThenInclude(e => e.Vehicle)
            .Include(v => v.Entries)
                .ThenInclude(e => e.Prerequisites)
            .SingleOrDefaultAsync(
                v => v.Id == request.ResearchTreeVersionId,
                cancellationToken);

        if (version is null)
        {
            throw new ResearchTreeVersionNotFoundException(request.ResearchTreeVersionId);
        }

        var entries = version.Entries.ToList();
        var entryByVehicleId = entries.ToDictionary(e => e.VehicleId);

        if (!entryByVehicleId.TryGetValue(request.TargetVehicleId, out var targetEntry))
        {
            throw new ResearchCalculationInputException(
                $"Target vehicle '{request.TargetVehicleId}' is not present in research tree version " +
                $"'{request.ResearchTreeVersionId}'.");
        }

        if (targetEntry.AcquisitionType != VehicleAcquisitionType.Researchable)
        {
            throw new ResearchCalculationInputException(
                $"Target vehicle '{request.TargetVehicleId}' is not researchable (acquisition type: '{targetEntry.AcquisitionType}'). Only researchable vehicles can be researched.");
        }

        var invalidOwnedIds = unlockedSet
            .Where(id => !entryByVehicleId.ContainsKey(id))
            .OrderBy(id => id)
            .ToList();
        if (invalidOwnedIds.Count > 0)
        {
            throw new ResearchCalculationInputException(
                $"Unlocked vehicle IDs are not present in research tree version " +
                $"'{request.ResearchTreeVersionId}': {string.Join(", ", invalidOwnedIds)}.");
        }

        var invalidFillerIds = fillerTargetIds
            .Where(id => !entryByVehicleId.ContainsKey(id))
            .OrderBy(id => id)
            .ToList();
        if (invalidFillerIds.Count > 0)
        {
            throw new ResearchCalculationInputException(
                $"Filler target IDs are not present in research tree version " +
                $"'{request.ResearchTreeVersionId}': {string.Join(", ", invalidFillerIds)}.");
        }

        var nonResearchableFillerIds = fillerTargetIds
            .Where(id => entryByVehicleId.TryGetValue(id, out var entry) && entry.AcquisitionType != VehicleAcquisitionType.Researchable)
            .OrderBy(id => id)
            .ToList();
        if (nonResearchableFillerIds.Count > 0)
        {
            throw new ResearchCalculationInputException(
                $"Filler target IDs must be researchable: {string.Join(", ", nonResearchableFillerIds)}.");
        }

        var ranks = version.TreeRanks.ToList();
        var ranksById = ranks.ToDictionary(rank => rank.Id);
        var entryWithInvalidRank = entries.FirstOrDefault(e => !ranksById.ContainsKey(e.TreeRankId));
        if (entryWithInvalidRank is not null)
        {
            throw new InvalidOperationException(
                $"Vehicle tree entry '{entryWithInvalidRank.Id}' references a rank outside research tree version " +
                $"'{request.ResearchTreeVersionId}'.");
        }

        var vehicles = entries.Select(e => e.Vehicle).ToList();
        var vehicleMap = vehicles.ToDictionary(v => v.Id);
        var vehiclesByRank = entries.GroupBy(e => e.TreeRankId).ToDictionary(g => g.Key, g => g.Select(e => e.Vehicle).ToList());

        // VehicleId -> list of prerequisite vehicle ids (dependency direction points up the tree).
        // Edges are entry-based; translated to vehicle ids via the version's entry map.
        var entryIdToVehicleId = entries.ToDictionary(e => e.Id, e => e.VehicleId);
        var prereqMap = entries
            .SelectMany(e => e.Prerequisites)
            .GroupBy(vp => entryIdToVehicleId[vp.VehicleTreeEntryId])
            .ToDictionary(
                g => g.Key,
                g => g.Select(vp => entryIdToVehicleId[vp.PrerequisiteVehicleTreeEntryId]).ToList());

        // ------------------------------------------------------------------
        // Step 1: Direct line traversal (upward graph search).
        //
        // Starting from the target vehicle, recursively collect every mandatory
        // parent defined by the explicit prerequisite edges. A branch stops as
        // soon as a vehicle has no prerequisites (e.g. a broken column line at
        // Rank IV). Vehicles already present in UnlockedVehicleIds are excluded
        // from the required set.
        // ------------------------------------------------------------------
        var required = new List<Vehicle>();
        var requiredIds = new HashSet<Guid>();
        var visited = new HashSet<Guid>();

        void CollectLine(Guid vehicleId)
        {
            // Unknown vehicle (outside the nation graph) or already traversed.
            if (!vehicleMap.TryGetValue(vehicleId, out var vehicle) || !visited.Add(vehicleId))
            {
                return;
            }

            if (unlockedSet.Contains(vehicleId)) return;

            if (!unlockedSet.Contains(vehicleId))
            {
                requiredIds.Add(vehicleId);
                required.Add(vehicle);
            }

            // No prerequisites -> the line is broken and traversal stops here.
            if (prereqMap.TryGetValue(vehicleId, out var prereqIds))
            {
                foreach (var prereqId in prereqIds)
                {
                    CollectLine(prereqId);
                }
            }
        }

        CollectLine(targetEntry.VehicleId);

        // ------------------------------------------------------------------
        // Step 1b: Collect explicit filler targets and their line prerequisites.
        //
        // Each player-chosen filler vehicle is added along with its full
        // prerequisite chain. Filler prereqs that overlap with the mandatory
        // line (requiredIds) are kept as mandatory (not double-counted).
        // ------------------------------------------------------------------
        var fillerIds = new HashSet<Guid>();
        var fillerVisited = new HashSet<Guid>();
        var fillerVehicles = new List<Vehicle>();

        void CollectFillerLine(Guid vehicleId)
        {
            if (!vehicleMap.TryGetValue(vehicleId, out var vehicle)
                || !fillerVisited.Add(vehicleId))
                return;

            // Already unlocked - skip.
            if (unlockedSet.Contains(vehicleId))
                return;

            // Already part of the mandatory line - no need to also track as filler.
            if (requiredIds.Contains(vehicleId))
            {
                // Still recurse into prerequisites in case they're not in the line.
                if (prereqMap.TryGetValue(vehicleId, out var prereqIds))
                {
                    foreach (var prereqId in prereqIds)
                    {
                        CollectFillerLine(prereqId);
                    }
                }
                return;
            }

            fillerIds.Add(vehicleId);
            fillerVehicles.Add(vehicle);

            // Recurse into prerequisites.
            if (prereqMap.TryGetValue(vehicleId, out var fillerPrereqIds))
            {
                foreach (var prereqId in fillerPrereqIds)
                {
                    CollectFillerLine(prereqId);
                }
            }
        }

        foreach (var fillerId in fillerTargetIds)
        {
            CollectFillerLine(fillerId);
        }

        // ------------------------------------------------------------------
        // Step 1c: Auto-select rank-gate filler candidates.
        //
        // A local traversal helper that behaves like CollectFillerLine, but
        // adds visited ids to the shared fillerVisited/fillerIds/fillerVehicles
        // collections so the main filler path and the auto-selection path
        // share de-duplication state.
        // ------------------------------------------------------------------
        void CollectAutoFillerLine(Guid vehicleId)
        {
            if (!vehicleMap.TryGetValue(vehicleId, out var vehicle)
                || !fillerVisited.Add(vehicleId))
                return;

            if (unlockedSet.Contains(vehicleId))
                return;

            if (requiredIds.Contains(vehicleId))
            {
                if (prereqMap.TryGetValue(vehicleId, out var prereqIds))
                {
                    foreach (var prereqId in prereqIds)
                    {
                        CollectAutoFillerLine(prereqId);
                    }
                }
                return;
            }

            fillerIds.Add(vehicleId);
            fillerVehicles.Add(vehicle);

            if (prereqMap.TryGetValue(vehicleId, out var autoFillerPrereqIds))
            {
                foreach (var prereqId in autoFillerPrereqIds)
                {
                    CollectAutoFillerLine(prereqId);
                }
            }
        }

        // Helper to simulate which additional vehicles would be added as fillers
        // if a candidate were selected, without mutating calculator state.
        List<Vehicle> GetCandidateChain(Guid vehicleId)
        {
            var chainVisited = new HashSet<Guid>(fillerVisited);
            var chain = new List<Vehicle>();

            void TraverseChain(Guid vId)
            {
                if (!vehicleMap.TryGetValue(vId, out var vehicle)
                    || !chainVisited.Add(vId))
                    return;

                if (unlockedSet.Contains(vId))
                    return;

                if (requiredIds.Contains(vId))
                {
                    if (prereqMap.TryGetValue(vId, out var prereqIds))
                    {
                        foreach (var prereqId in prereqIds)
                        {
                            TraverseChain(prereqId);
                        }
                    }
                    return;
                }

                if (!fillerIds.Contains(vId))
                {
                    chain.Add(vehicle);
                }

                if (prereqMap.TryGetValue(vId, out var autoFillerPrereqIds))
                {
                    foreach (var prereqId in autoFillerPrereqIds)
                    {
                        TraverseChain(prereqId);
                    }
                }
            }

            TraverseChain(vehicleId);
            return chain;
        }

        // ------------------------------------------------------------------
        // Step 2: Rank gate verification (Rank I up to TargetRank - 1).
        //
        // Evaluate each rank sequentially. Count unique vehicles that are
        // either already unlocked, part of the mandatory line, or part of the
        // explicit/auto filler set. When a shortfall remains after explicit
        // fillers, auto-select eligible researchable candidates in that rank
        // according to the caller's selected ResearchOptimizationMode.
        // Any remaining deficit after exhausting candidates is recorded in
        // RankDeficits; evaluation continues to higher ranks so the caller
        // sees all rank-gate issues in one pass.
        // ------------------------------------------------------------------
        // Build an index of entries by rank for efficient candidate lookup.
        var entriesByRankId = entries
            .GroupBy(e => e.TreeRankId)
            .ToDictionary(g => g.Key, g => g.ToList());

        var targetRankNumber = ranksById[targetEntry.TreeRankId].RankNumber;
        var rankDeficits = new List<RankDeficitDto>();

        foreach (var rank in ranks
            .Where(r => r.RankNumber < targetRankNumber)
            .OrderBy(r => r.RankNumber))
        {
            var threshold = rank.RequiredVehiclesUnlocked;
            if (threshold <= 0)
            {
                continue;
            }

            var rankVehicles = vehiclesByRank.TryGetValue(rank.Id, out var rv) ? rv : new List<Vehicle>();

            var count = rankVehicles.Count(v =>
                unlockedSet.Contains(v.Id)
                || requiredIds.Contains(v.Id)
                || fillerIds.Contains(v.Id));

            var shortfall = threshold - count;
            if (shortfall <= 0)
            {
                continue;
            }

            var rankEntries = entriesByRankId.TryGetValue(rank.Id, out var re) ? re : new List<VehicleTreeEntry>();

            while (shortfall > 0)
            {
                var eligibleCandidates = rankEntries
                    .Where(e =>
                        e.AcquisitionType == VehicleAcquisitionType.Researchable
                        && !unlockedSet.Contains(e.VehicleId)
                        && !requiredIds.Contains(e.VehicleId)
                        && !fillerIds.Contains(e.VehicleId))
                    .ToList();

                if (eligibleCandidates.Count == 0)
                {
                    break;
                }

                VehicleTreeEntry bestCandidate;
                switch (request.OptimizationMode)
                {
                    case ResearchOptimizationMode.LeastRp:
                        // Match Batch 10 greedy baseline: lowest RP, lowest SL, name tie-break.
                        bestCandidate = eligibleCandidates
                            .OrderBy(e => e.RpCost)
                            .ThenBy(e => e.SlCost)
                            .ThenBy(e => e.Vehicle.Name)
                            .First();
                        break;

                    case ResearchOptimizationMode.LeastSl:
                        // Minimize vehicle purchase SL cost: lowest SL, lowest RP, name tie-break.
                        bestCandidate = eligibleCandidates
                            .OrderBy(e => e.SlCost)
                            .ThenBy(e => e.RpCost)
                            .ThenBy(e => e.Vehicle.Name)
                            .First();
                        break;

                    case ResearchOptimizationMode.FewestVehicles:
                        // Minimize total additional filler vehicles added (including prerequisite chain).
                        bestCandidate = eligibleCandidates
                            .Select(e => new { Entry = e, Chain = GetCandidateChain(e.VehicleId) })
                            .OrderBy(x => x.Chain.Count)
                            .ThenBy(x => x.Chain.Sum(v => (long)entryByVehicleId[v.Id].RpCost))
                            .ThenBy(x => x.Chain.Sum(v => (long)entryByVehicleId[v.Id].SlCost))
                            .ThenBy(x => x.Entry.Vehicle.Name)
                            .First()
                            .Entry;
                        break;

                    case ResearchOptimizationMode.FewestMatches:
                        // Minimize estimated matches: max(ceil(TotalRP / avgRP), ceil(TotalSL / avgSL)).
                        var currentTotalRp = required.Sum(v => (long)entryByVehicleId[v.Id].RpCost)
                            + fillerVehicles.Sum(v => (long)entryByVehicleId[v.Id].RpCost);
                        var currentTotalSl = required.Sum(v => (long)entryByVehicleId[v.Id].SlCost)
                            + fillerVehicles.Sum(v => (long)entryByVehicleId[v.Id].SlCost);

                        bestCandidate = eligibleCandidates
                            .Select(e =>
                            {
                                var chain = GetCandidateChain(e.VehicleId);
                                var addRp = chain.Sum(v => (long)entryByVehicleId[v.Id].RpCost);
                                var addSl = chain.Sum(v => (long)entryByVehicleId[v.Id].SlCost);
                                var projRp = currentTotalRp + addRp;
                                var projSl = currentTotalSl + addSl;
                                var rpMatches = DivideRoundUp(projRp, request.AverageRpPerMatch);
                                var slMatches = DivideRoundUp(projSl, request.AverageNetSlPerMatch);
                                var matches = Math.Max(rpMatches, slMatches);
                                return new
                                {
                                    Entry = e,
                                    Matches = matches,
                                    AddRp = addRp,
                                    AddSl = addSl
                                };
                            })
                            .OrderBy(x => x.Matches)
                            .ThenBy(x => x.AddRp)
                            .ThenBy(x => x.AddSl)
                            .ThenBy(x => x.Entry.Vehicle.Name)
                            .First()
                            .Entry;
                        break;

                    default:
                        throw new ArgumentOutOfRangeException(
                            nameof(request.OptimizationMode),
                            $"Unknown research optimization mode: {request.OptimizationMode}");
                }

                CollectAutoFillerLine(bestCandidate.VehicleId);

                count = rankVehicles.Count(v =>
                    unlockedSet.Contains(v.Id)
                    || requiredIds.Contains(v.Id)
                    || fillerIds.Contains(v.Id));
                shortfall = threshold - count;
            }

            if (shortfall > 0)
            {
                rankDeficits.Add(new RankDeficitDto(
                    rank.RankNumber,
                    shortfall,
                    threshold));
            }
        }

        // ------------------------------------------------------------------
        // Step 3: Total remaining costs = mandatory line vehicles + explicit fillers.
        // ------------------------------------------------------------------
        var requiredVehicleSummaries = new List<VehicleRpSummary>(required.Count + fillerVehicles.Count);
        requiredVehicleSummaries.AddRange(required.Select(v =>
            new VehicleRpSummary(
                v.Id,
                v.Name,
                entryByVehicleId[v.Id].RpCost,
                entryByVehicleId[v.Id].SlCost,
                false)));
        requiredVehicleSummaries.AddRange(fillerVehicles.Select(v =>
            new VehicleRpSummary(
                v.Id,
                v.Name,
                entryByVehicleId[v.Id].RpCost,
                entryByVehicleId[v.Id].SlCost,
                true)));

        var totalRp = requiredVehicleSummaries.Sum(v => (long)v.RpRemaining);
        var totalSl = requiredVehicleSummaries.Sum(v => (long)v.SlRemaining);
        var rpEstimatedMatches = DivideRoundUp(totalRp, request.AverageRpPerMatch);
        var slEstimatedMatches = DivideRoundUp(totalSl, request.AverageNetSlPerMatch);
        var estimatedMatches = Math.Max(rpEstimatedMatches, slEstimatedMatches);

        return new ResearchCalculationResult(
            targetEntry.VehicleId,
            totalRp,
            totalSl,
            rpEstimatedMatches,
            slEstimatedMatches,
            estimatedMatches,
            requiredVehicleSummaries,
            rankDeficits);
    }

    private static long DivideRoundUp(long total, int amountPerMatch)
    {
        if (total == 0)
        {
            return 0;
        }

        return total / amountPerMatch + (total % amountPerMatch == 0 ? 0 : 1);
    }
}
